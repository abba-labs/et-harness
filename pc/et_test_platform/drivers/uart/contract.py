# UART PC Driver Package 的contract层。
#
# 职责：提供 UART 的已发布 Service/Command/Wire 常量。
# 边界：不发送请求、不解析 Capability，也不承载运行时策略。
# 依赖：仅依赖标准库 Enum 与 ET Message 长度上限。

from enum import IntEnum

from ...communication.protocols.et_message import MAX_BODY as ET_MESSAGE_MAX_BODY

UART_SERVICE_ID = 0x0101

MAX_NINE_BIT_WORDS = 256
MAX_CAPTURE_BYTES = 512
UART_WRITE_REQUEST_OVERHEAD = 4
MAX_WRITE_CHUNK_BYTES = ET_MESSAGE_MAX_BODY - UART_WRITE_REQUEST_OVERHEAD
MAX_READ_CHUNK_BYTES = ET_MESSAGE_MAX_BODY
MAX_PARTIAL_WRITE_BYTES = ET_MESSAGE_MAX_BODY
DEFAULT_IO_TIMEOUT_S = 2.0
DEFAULT_IO_POLL_INTERVAL_S = 0.0005

UART_CPR_FIFO_STAT = 1 << 10
UART_CPR_FIFO_ACCESS = 1 << 9
UART_CPR_SHADOW = 1 << 11


# 定义 UartCommand 的已发布 Wire/Command 语义；编号和取值属于兼容合同，不得静默复用或改义。
class UartCommand(IntEnum):
    CAPABILITIES_GET = 0x0001
    DMA_ENDPOINT_GET = 0x0002
    DMA_ENABLE_SET = 0x0003
    INITIALIZE = 0x0004
    DEINITIALIZE = 0x0005
    WRITE = 0x0006
    READ_EXACT = 0x0007
    CAPTURE_START = 0x0008
    CAPTURE_GET = 0x0009
    CAPTURE_CANCEL = 0x000A
    EXCHANGE = 0x000B
    SNAPSHOT_GET = 0x000C
    SOFTWARE_RESET = 0x000D
    LOOPBACK_SET = 0x000E
    FIFO_CONFIG = 0x000F
    STATUS_GET = 0x0010
    IRQ_CONFIG = 0x0011
    IRQ_STATE_GET = 0x0012
    BREAK_SET = 0x0013
    HALT_SET = 0x0014
    DMA_MODE_SET = 0x0015
    NINE_BIT_CONFIG = 0x0016
    WRITE_9BIT = 0x0017
    READ_9BIT = 0x0018
    FLOW_CONTROL_SET = 0x0019
    MODEM_CONTROL_SET = 0x001A
    MODEM_STATUS_GET = 0x001B
    WRITE_PARTIAL = 0x001C
    BUSY_DETECT_TRIGGER = 0x001D
    SHADOW_FIFO_CONFIG = 0x001E
    FIFO_ACCESS_SET = 0x001F
    FIFO_TX_READ = 0x0020
    FIFO_RX_WRITE = 0x0021
