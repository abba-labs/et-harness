# AES Firmware Service Wire 合同。
#
# 职责：发布稳定 Service/Command ID 和精确 Body 尺寸。
# 边界：不构造请求、不访问 TargetClient，也不实现能力查询或运行策略。
# 依赖：仅依赖 Python 标准库 Enum。

from enum import IntEnum

AES_SERVICE_ID = 0x0103
AES_SERVICE_API_VERSION = 1
AES_BLOCK_SIZE = 16
AES_CAPABILITIES_SIZE = 32
AES_CONFIGURE_SIZE = 12
AES_KEY_SET_SIZE = 36
AES_IV_SIZE = 16
AES_DATA_LENGTH_SIZE = 8
AES_PROCESS_SIZE = 20
AES_STATUS_SIZE = 8
AES_IRQ_SNAPSHOT_SIZE = 28
AES_PROCESS_RESULT_SIZE = 12
AES_IRQ_TRANSFER_STATUS_SIZE = 24
AES_TIMED_RESULT_SIZE = 16


# AES Service 的稳定命令编号；数值同时由固件和协议单测冻结。
class AesCommand(IntEnum):
    CAPABILITIES_GET = 0x0001
    ENABLE = 0x0002
    DISABLE = 0x0003
    CONFIGURE = 0x0004
    KEY_SET = 0x0005
    IV_SET = 0x0006
    IV_GET = 0x0007
    DATA_LENGTH_SET = 0x0008
    DATA_LENGTH_GET = 0x0009
    PROCESS = 0x000A
    STATUS_GET = 0x000B
    STATUS_CLEAR = 0x000C
    IRQ_ENABLE = 0x000D
    IRQ_DISABLE = 0x000E
    IRQ_MASK = 0x000F
    IRQ_UNMASK = 0x0010
    IRQ_FORCE = 0x0011
    IRQ_CLEAR = 0x0012
    IRQ_SNAPSHOT_GET = 0x0013
    DMA_REQUEST_SET = 0x0014
    IRQ_TRANSFER_START = 0x0015
    IRQ_TRANSFER_STATUS_GET = 0x0016
    IRQ_TRANSFER_ABORT = 0x0017
    TIMED_PROCESS = 0x0018
    BLOCK_WRITE = 0x0019
    BLOCK_READ = 0x001A
    BLOCK_WRITE_DIRECT = 0x001B
    BLOCK_WRITE_PAIR_DIRECT = 0x001C
    BLOCK_WRITE_DISABLE_DIRECT = 0x001D
