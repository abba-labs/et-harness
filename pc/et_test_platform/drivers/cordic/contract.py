# CORDIC PC Driver Package 的 contract 层。
#
# 职责：定义 CORDIC 已发布的 Service、Command 和 Wire 常量。
# 边界：不发送请求、不解析响应、不承载运行时或测试策略。
# 依赖：仅依赖标准库 Enum。

from enum import IntEnum

CORDIC_SERVICE_ID = 0x0104
CORDIC_SERVICE_API_VERSION = 1
CORDIC_CAPABILITIES_SIZE = 16
CORDIC_TIMED_REQUEST_SIZE = 16
CORDIC_TIMED_RESPONSE_SIZE = 12


# CORDIC Firmware Service 已发布命令编号。
class CordicCommand(IntEnum):
    CAPABILITIES_GET = 0x0001
    CONFIGURE = 0x0002
    ARGUMENT_SUBMIT = 0x0003
    RESULT_GET = 0x0004
    STATUS_GET = 0x0005
    STATUS_CLEAR = 0x0006
    ARGUMENT_COUNT_GET = 0x0007
    CONVERSION_STATUS_GET = 0x0008
    CONVERSION_STATUS_CLEAR = 0x0009
    IRQ_ENABLE = 0x000A
    IRQ_DISABLE = 0x000B
    IRQ_MASK = 0x000C
    IRQ_UNMASK = 0x000D
    IRQ_FORCE = 0x000E
    IRQ_CLEAR = 0x000F
    IRQ_SNAPSHOT_GET = 0x0010
    ZERO_OVERHEAD_EXECUTE = 0x0011
    TEST_EXECUTE_TIMED = 0x0012
