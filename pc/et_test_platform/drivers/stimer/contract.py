# STIMER Wire常量与命令编号。
# 职责：冻结STIMER Service公开二进制布局。
# 边界：不执行I/O，不包含芯片地址或IRQ号。
# 依赖：仅依赖标准库 IntEnum 和 Struct。

from enum import IntEnum
from struct import Struct

STIMER_SERVICE_ID = 0x0106
STIMER_SERVICE_API_VERSION = 3

CAPABILITIES_STRUCT = Struct("<HHIIHBBI")
CONFIG_STRUCT = Struct("<IHBB4x")
UINT32_STRUCT = Struct("<I")
COMPARE_STRUCT = Struct("<B3xI")
EVENT_PULSE_WIDTH_STRUCT = Struct("<IH2x")
DEBUG_HALT_POLICY_STRUCT = Struct("<B3x")
EMERGENCY_ROUTE_STRUCT = Struct("<BB2x")
IRQ_SNAPSHOT_STRUCT = Struct("<IIIIII")


# STIMER Service 公开命令编号，与 Firmware Contract 逐值对应。
class StimerCommand(IntEnum):
    CAPABILITIES_GET = 0x0001
    CONFIGURE = 0x0002
    START = 0x0003
    STOP = 0x0004
    PAUSE = 0x0005
    RESUME = 0x0006
    CLEAR = 0x0007
    RELOAD = 0x0008
    LIVE_COUNT_GET = 0x0009
    LATCHED_COUNT_GET = 0x000A
    STATUS_GET = 0x000B
    COMPARE_SET = 0x000C
    IRQ_ENABLE = 0x000D
    IRQ_DISABLE = 0x000E
    IRQ_MASK = 0x000F
    IRQ_UNMASK = 0x0010
    IRQ_FORCE = 0x0011
    IRQ_CLEAR = 0x0012
    IRQ_SNAPSHOT_GET = 0x0013
    EVENT_PULSE_WIDTH_SET = 0x0014
    DMA_REQUEST_SELECT = 0x0015
    DEBUG_HALT_POLICY_SET = 0x0016
    EMERGENCY_CAPTURE_CONFIGURE = 0x0017
    EMERGENCY_CAPTURE_GET = 0x0018
    EMERGENCY_CAPTURE_CLEAR = 0x0019
