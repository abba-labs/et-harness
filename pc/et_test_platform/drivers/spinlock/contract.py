# SPINLOCK Wire 常量与命令编号。
# 职责：冻结 SPINLOCK Service 的公开二进制布局。
# 边界：不执行 I/O，不包含芯片寄存器、地址或 Master 拓扑。
# 依赖：仅依赖标准库。

from enum import IntEnum
from struct import Struct

SPINLOCK_SERVICE_ID = 0x0108
SPINLOCK_SERVICE_API_VERSION = 2

CAPABILITIES_STRUCT = Struct("<HHIHH")
CONFIG_STRUCT = Struct("<BB2x")
MASTER_ID_STRUCT = Struct("<H")
RESOURCE_REQUEST_STRUCT = Struct("<HH")
RESOURCE_ID_STRUCT = Struct("<H")
FLAG_SNAPSHOT_STRUCT = Struct("<II")
RESOURCE_SNAPSHOT_STRUCT = Struct("<BBBBHH")
CLEAR_PROBE_STRUCT = Struct("<BB2x")
PEER_STATUS_STRUCT = Struct("<BBH")
PEER_JOB_CONFIG_STRUCT = Struct("<BBHH2xI")
PEER_JOB_SNAPSHOT_STRUCT = Struct("<BBHII")
PEER_CONTROL_STRUCT = Struct("<B3x")
LOCAL_STRESS_REQUEST_STRUCT = Struct("<H2xI")
LOCAL_STRESS_RESPONSE_STRUCT = Struct("<I")
SHARED_SNAPSHOT_STRUCT = Struct("<II")


