    RESOURCE_ACQUIRE_TRY = 0x0010
    RESOURCE_RELEASE = 0x0011
    FLAG_SNAPSHOT_GET = 0x0012
    RESOURCE_SNAPSHOT_GET = 0x0013
    BATCH_RELEASE = 0x0020
    GLOBAL_RELEASE = 0x0021
    CLEAR_KEY_PROBE = 0x0022
    PEER_STATUS_GET = 0x0030
    PEER_JOB_START = 0x0031
    PEER_JOB_SNAPSHOT_GET = 0x0032
    PEER_JOB_CONTROL = 0x0033
    SHARED_STRESS_RESET = 0x0034
    LOCAL_STRESS_RUN = 0x0035
    SHARED_SNAPSHOT_GET = 0x0036
