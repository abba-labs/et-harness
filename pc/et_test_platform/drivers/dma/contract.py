# DMA PC Driver Package 的contract层。
#
# 职责：提供 DMA 的已发布 Service/Command/Wire 常量。
# 边界：不发送请求、不解析 Capability，也不承载运行时策略。
# 依赖：仅依赖标准库 Enum。

from enum import IntEnum

DMA_SERVICE_ID = 0x0100


# DMA Firmware Service 已发布命令编号。
class DmaCommand(IntEnum):
    CAPABILITIES_GET = 0x0001
    CONTROLLER_ENABLE = 0x0002
    CONTROLLER_DISABLE = 0x0003
    CHANNEL_CONFIGURE = 0x0004
    CHANNEL_DECONFIGURE = 0x0005
    CHANNEL_START = 0x0006
    CHANNEL_STOP = 0x0007
    CHANNEL_STATUS_GET = 0x0008
    IRQ_ENABLE = 0x0009
    IRQ_DISABLE = 0x000A
    IRQ_RESULT_GET = 0x000B
    IRQ_RESULT_CLEAR = 0x000C
    CHANNEL_SUSPEND = 0x000D
    CHANNEL_RESUME = 0x000E
    FREE_CHANNEL_FIND = 0x000F
    CHANNELS_START = 0x0010
    COMPONENT_SNAPSHOT_GET = 0x0011
    INTERRUPT_SNAPSHOT_GET = 0x0012
    CHANNEL_SNAPSHOT_GET = 0x0013
    LLI_DESCRIPTOR_INIT = 0x0014
    INTERRUPT_MASK_ENABLE = 0x0015
    INTERRUPT_MASK_DISABLE = 0x0016
    INTERRUPT_PENDING_CLEAR = 0x0017
    CHANNEL_START_WAIT = 0x0018
    IRQ_COMBINED_ENABLE = 0x0019
    SOFTWARE_HANDSHAKE_REQUEST_SET = 0x001A
    CHANNELS_START_WAIT_ORDER = 0x001B
    LLI_DESCRIPTOR_INIT_V2 = 0x001C
    CHANNEL_START_TIMED = 0x001D
    TIMING_SNAPSHOT_GET = 0x001E
